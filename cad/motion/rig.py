#!/usr/bin/env python3
"""The VT350's rig for platform/freecad/timeline.py: from the committed CAD logs and the tool-change config (vt350#135).

    python3 cad/motion/rig.py --check     # rig.json == what the logs and config give; "rig: OK"
    python3 cad/motion/rig.py --write     # regenerate rig.json

Where each number comes from:
  xy                cad/klipper/xy_mapping.json (PROPOSED in vt350#116)
  bed top_dz        sweep_toolhead.log "<head> carried: ... bed top dZ +93.32" (both heads must agree)
  heads nozzle      sweep_toolhead.log "<head>: docked nozzle tip (x, y, z)"
  heads pickup      sweep_toolhead.log "<head>: pickup carriage offset (x, y, z) from the gantry carriage"
  heads dock        the docked nozzle in printer XY; X must be the tool's params_park_x in cad/klipper/toolchanger.cfg
  heads into        toward params_attach_y: the carriage pushes the head that way to the keyslots' large opening
The group names are the keys of cad/studies/sweep_toolhead.py's plan: bed, gantry, belt, carriage, and one per head.

This file is VT350-specific. Plain python3, standard library only.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KLIPPER = os.path.join(os.path.dirname(HERE), "klipper")
sys.path.insert(0, KLIPPER)
import dock_params  # noqa: E402
import limits  # noqa: E402

RIG = os.path.join(HERE, "rig.json")
NUM = r"(-?[0-9.]+)"


def _per_head(pattern, sweep_log, what):
    got = {h: tuple(float(v) for v in vals) for h, *vals in re.findall(pattern, sweep_log)}
    if set(got) != set(dock_params.HEADS):
        raise ValueError(f"sweep_toolhead log: need a '{what}' line for each of {sorted(dock_params.HEADS)}: {got}")
    return got


def derive(sweep_log, mapping, dock):
    """The rig, as timeline.py reads it. dock is dock_params.derive()'s output (the committed toolchanger.cfg's)."""
    pickup = _per_head(rf"(\w+): pickup carriage offset \({NUM}, {NUM}, {NUM}\)", sweep_log, "pickup carriage offset")
    nozzle = _per_head(rf"(\w+): docked nozzle tip \({NUM}, {NUM}, {NUM}\)", sweep_log, "docked nozzle tip")
    top = {v[0] for v in _per_head(rf"(\w+) carried: .*?bed top dZ \+?{NUM}", sweep_log, "bed top dZ").values()}
    if len(top) != 1:
        raise ValueError(f"the heads give different bed top dZ: {sorted(top)}")
    (ox, oy), (sx, sy) = mapping["origin_model_xy"], mapping["sign_xy"]
    attach_y = dock["toolchanger"]["params_attach_y"]
    heads = {}
    for name, h in dock_params.HEADS.items():
        nx, ny, nz = nozzle[name]
        px, py = round(sx * (nx - ox), 6), round(sy * (ny - oy), 6)
        park_x = dock["tools"][h["tool"]]["params_park_x"]
        if park_x != px:
            raise ValueError(f"{h['tool']} park_x {park_x} isn't the {name} head's docked nozzle at printer X {px}")
        heads[name] = {"group": name, "tool": h["tool"], "nozzle": [nx, ny, nz], "pickup": list(pickup[name]),
                       "dock": [px, py], "into": [0, 1 if attach_y > py else -1]}
    return {"about": "VT350 rig for platform/freecad/timeline.py; generated by cad/motion/rig.py --write, don't edit",
            "xy": {"origin_model_xy": mapping["origin_model_xy"], "sign_xy": mapping["sign_xy"]},
            "bed": {"group": "bed", "top_dz": top.pop()},
            "gantry_groups": ["gantry", "belt"], "carriage_group": "carriage",
            "reference_head": "Left", "heads": heads}


def derive_committed():
    with open(os.path.join(limits.LOGS, "sweep_toolhead.log")) as f:
        return derive(f.read(), limits.load_mapping(), dock_params.derive_committed())


def main(argv):
    want = derive_committed()
    text = json.dumps(want, indent=2) + "\n"
    if argv == ["--write"]:
        with open(RIG, "w") as f:
            f.write(text)
        return [f"wrote {RIG}"]
    if argv == ["--check"]:
        with open(RIG) as f:
            have = f.read()
        if have != text:
            raise SystemExit("rig: FAILED: rig.json differs from the CAD logs and toolchanger.cfg; "
                             "run python3 cad/motion/rig.py --write")
        return [f"{h}: dock {v['dock']}, into {v['into']}" for h, v in want["heads"].items()] + ["rig: OK"]
    raise SystemExit(__doc__)


if __name__ == "__main__":
    print("\n".join(main(sys.argv[1:])))
