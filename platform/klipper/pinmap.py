#!/usr/bin/env python3
"""A Klipper/Kalico config's MCU pins, mapped onto simulated boards (vt350#224 AC3).

    python3 platform/klipper/pinmap.py generate --config printer.cfg --map pinmap.json
    python3 platform/klipper/pinmap.py check    --config printer.cfg --map pinmap.json      # "pinmap: OK"
    python3 platform/klipper/pinmap.py apply    --config printer.cfg --map pinmap.json --out DIR

A live klippy needs an MCU to talk to for every [mcu] section. With no hardware, each MCU becomes one simulated board
(simulavr running Kalico's AVR firmware built with CONFIG_SIMULAVR), keeping its [mcu <name>]; only its pins change.
`generate` reads the config and every file it [include]s (globs and relative paths as Kalico resolves them, a repeated
section's later option winning) and gives each MCU pin a pin on that MCU's simulated board: thermistor inputs on ADC
pins, hardware-PWM outputs on PWM pins, the rest anywhere free, the board's serial pins never. An existing map is kept
where it is still valid, so adding a pin doesn't move the others. `check` fails when the config uses a pin the map
doesn't cover, the map has a pin the config no longer uses, or an entry can't work on the board. `apply` writes a
copy of the config tree with every mapped pin rewritten (the source files are not touched).

Pins on a chip that isn't an MCU (probe:z_virtual_endstop, a [multi_pin]) are not mapped; nor are macro variables or
macro bodies. Not supported, and refused rather than guessed: [board_pins] aliases, and pull-downs (~), which an AVR
doesn't have.

Generic: no printer knowledge. Plain python3, standard library only.
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

# Simulated boards. Klipper's AVR firmware runs on simulavr for these chips (src/avr/Kconfig, SIMULAVR); klippy talks
# to it over UART0, so PD0/PD1 are never given out. ADC: PA0..PA7. Hardware PWM (src/avr/hard_pwm.c): OC0A PB3,
# OC0B PB4, OC1B PD4, OC1A PD5, OC2B PD6, OC2A PD7.
_PORT = [f"P{port}{i}" for port in "ABCD" for i in range(8)]
TARGETS = {
    "simulavr-atmega644p": {
        "pins": _PORT,
        "reserved": ["PD0", "PD1"],
        "adc": [f"PA{i}" for i in range(8)],
        "pwm": ["PB3", "PB4", "PD4", "PD5", "PD6", "PD7"],
        # where plain digital pins go first: ports without a special job, then the PWM pins, then the ADC pins
        "digital": ([f"PC{i}" for i in range(8)] + ["PB0", "PB1", "PB2", "PB5", "PB6", "PB7", "PD2", "PD3"]
                    + ["PB3", "PB4", "PD4", "PD5", "PD6", "PD7"] + [f"PA{i}" for i in range(7, -1, -1)]),
    },
}
DEFAULT_TARGET = "simulavr-atmega644p"
ABOUT = ("Generated by platform/klipper/pinmap.py generate from the config: real MCU pin -> pin on that MCU's "
         "simulated board. Don't edit by hand; pinmap.py check fails when it and the config differ.")

# sensor_types whose sensor_pin is an SPI chip select, not an analog input
SPI_SENSORS = {"max6675", "max31855", "max31856", "max31865"}

PinUse = collections.namedtuple("PinUse", "mcu pin kind where")

SECTION = re.compile(r"^\[([^\]]+)\]\s*(?:[#;].*)?$")
OPTION = re.compile(r"^([^\s:=#;][^:=]*?)\s*[:=](.*)$")
INLINE_COMMENT = re.compile(r"\s[#;]")


class Config:
    """A config and its includes: files in the order read, and every section's options, later ones winning."""

    def __init__(self):
        self.files = []                  # paths, in include order
        self.sections = {}               # name -> {option: value}


def _strip_comment(value):
    m = INLINE_COMMENT.search(value)
    return value[:m.start()] if m else value


def _read(path, cfg, stack):
    path = os.path.abspath(path)
    if path in stack:
        raise ValueError(f"include loop at {path}")
    cfg.files.append(path)
    section, option = None, None
    with open(path) as f:
        for raw in f.read().splitlines():
            if not raw.strip() or raw.lstrip()[0] in "#;":
                continue
            if raw[0].isspace():         # a continuation line of a multi-line option
                if section is not None and option is not None:
                    cfg.sections[section][option] += "\n" + _strip_comment(raw).strip()
                continue
            m = SECTION.match(raw)
            if m:
                name = m.group(1).strip()
                option = None
                if name.lower().startswith("include "):
                    pattern = os.path.join(os.path.dirname(path), name[len("include "):].strip())
                    found = sorted(glob.glob(pattern))
                    if not found and not glob.has_magic(pattern):
                        raise ValueError(f"{path}: include file {pattern} does not exist")
                    for inc in found:
                        _read(inc, cfg, stack | {path})
                    section = None
                    continue
                section = name
                cfg.sections.setdefault(section, {})
                continue
            m = OPTION.match(raw)
            if m and section is not None:
                option = m.group(1).strip().lower()
                cfg.sections[section][option] = _strip_comment(m.group(2)).strip()


def load(path):
    """The config at path, with its includes."""
    cfg = Config()
    _read(path, cfg, frozenset())
    return cfg


def is_pin_option(option):
    return (option in ("pin", "pins") or option.endswith("_pin") or option.endswith("_pins")) \
        and not option.startswith("variable_")


def split_pin(desc):
    """'^!o2s:PB3' -> ('^!', 'o2s', 'PB3'); no chip -> 'mcu'."""
    desc = desc.strip()
    mods = ""
    while desc and desc[0] in "^~!":
        mods += desc[0]
        desc = desc[1:].strip()
    chip, sep, pin = desc.partition(":")
    if not sep:
        chip, pin = "mcu", chip
    return mods, chip.strip(), "".join(pin.split())


def mcu_names(cfg):
    out = set()
    for name in cfg.sections:
        parts = name.split()
        if parts[0].lower() == "mcu" and len(parts) <= 2:
            out.add(parts[1] if len(parts) == 2 else "mcu")
    return out


def _kind(section, opts, option):
    if option == "sensor_pin" and opts.get("sensor_type", "").strip().lower() not in SPI_SENSORS:
        return "adc"
    if option == "pin" and "analog_range" in opts:
        return "adc"
    if option == "pin" and opts.get("hardware_pwm", "").strip().lower() in ("true", "1", "yes"):
        return "pwm"
    return "digital"


def pin_uses(cfg):
    """Every MCU pin the config uses: [PinUse(mcu, pin, kind, where)], kind adc, pwm or digital."""
    mcus = mcu_names(cfg)
    out = []
    for section, opts in cfg.sections.items():
        if section.split()[0].lower() == "board_pins":
            raise ValueError(f"[{section}]: board_pins aliases aren't supported; write the pins out")
        for option, value in opts.items():
            if not is_pin_option(option) or not value:
                continue
            for desc in value.split(","):
                if not desc.strip():
                    continue
                mods, chip, pin = split_pin(desc)
                if chip not in mcus:
                    continue
                if "~" in mods:
                    raise ValueError(f"[{section}] {option}: {desc.strip()}: a pull-down (~) has no simulated "
                                     "equivalent (an AVR has pull-ups only)")
                out.append(PinUse(chip, pin, _kind(section, opts, option), f"[{section}] {option}"))
    return out


def _natural(s):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def _needs(uses):
    """{mcu: {pin: kind}}, one kind per pin (adc or pwm wins over digital; adc and pwm together is an error)."""
    out = {}
    for u in uses:
        have = out.setdefault(u.mcu, {}).get(u.pin)
        if have and have != u.kind and "digital" not in (have, u.kind):
            raise ValueError(f"{u.mcu}:{u.pin} is used as both {have} and {u.kind}")
        if have is None or have == "digital":
            out[u.mcu][u.pin] = u.kind
    return out


def valid_for(board, kind, sim):
    return sim in board["pins"] and sim not in board["reserved"] and (kind == "digital" or sim in board[kind])


def generate(uses, previous=None, target=DEFAULT_TARGET):
    """The map {"target": ..., "mcus": {mcu: {real pin: simulated pin}}}; previous assignments kept where valid."""
    board = TARGETS[target]
    free_count = len(board["pins"]) - len(board["reserved"])
    prev = (previous or {}).get("mcus", {}) if (previous or {}).get("target") == target else {}
    mcus = {}
    for mcu, needs in sorted(_needs(uses).items()):
        if len(needs) > free_count:
            raise ValueError(f"{mcu} needs {len(needs)} pins; one {target} has {free_count}")
        got, taken = {}, set()
        for pin, sim in prev.get(mcu, {}).items():
            if pin in needs and sim not in taken and valid_for(board, needs[pin], sim):
                got[pin] = sim
                taken.add(sim)
        order = {"adc": 0, "pwm": 1, "digital": 2}
        for pin in sorted((p for p in needs if p not in got), key=lambda p: (order[needs[p]], _natural(p))):
            kind = needs[pin]
            pool = [s for s in board[kind] if s not in taken and s not in board["reserved"]]
            if not pool:
                raise ValueError(f"{mcu}:{pin}: no {kind} pin left on {target}")
            got[pin] = pool[0]
            taken.add(pool[0])
        mcus[mcu] = {p: got[p] for p in sorted(got, key=_natural)}
    return {"about": ABOUT, "target": target, "mcus": mcus}


def check(uses, m):
    """Problems with map m for these pin uses: [] when it covers them all, exactly, and every entry can work."""
    target = m.get("target")
    if target not in TARGETS:
        return [f"unknown target {target!r}: one of {sorted(TARGETS)}"]
    board = TARGETS[target]
    mapped = m.get("mcus", {})
    problems = []
    try:
        needs = _needs(uses)
    except ValueError as e:
        return [str(e)]
    seen = set()
    for u in uses:
        if (u.mcu, u.pin) in seen:
            continue
        seen.add((u.mcu, u.pin))
        sim = mapped.get(u.mcu, {}).get(u.pin)
        if sim is None:
            problems.append(f"{u.mcu}:{u.pin} ({u.where}) is not in the map")
        elif not valid_for(board, needs[u.mcu][u.pin], sim):
            problems.append(f"{u.mcu}:{u.pin} -> {sim}: not a usable {needs[u.mcu][u.pin]} pin on {target}")
    for mcu, pins in mapped.items():
        for pin in pins:
            if (mcu, pin) not in seen:
                problems.append(f"{mcu}:{pin} is in the map but the config doesn't use it")
        dup = [s for s, n in collections.Counter(pins.values()).items() if n > 1]
        if dup:
            problems.append(f"{mcu}: simulated pin(s) {', '.join(sorted(dup))} given out twice")
    return problems


def rewrite_value(desc, m):
    """One pin description with its pin swapped for the simulated one; modifiers, chip and spacing kept."""
    mods, chip, pin = split_pin(desc)
    sim = m["mcus"].get(chip, {}).get(pin)
    if sim is None:
        return desc
    lead = desc[:len(desc) - len(desc.lstrip())]
    trail = desc[len(desc.rstrip()):]
    return f"{lead}{mods}{chip + ':' if ':' in desc else ''}{sim}{trail}"


def _rewrite_line(raw, m):
    if not raw or raw[0].isspace() or raw.lstrip()[:1] in ("#", ";", "["):
        return raw
    om = OPTION.match(raw)
    if not om or not is_pin_option(om.group(1).strip().lower()):
        return raw
    head = raw[:om.start(2)]
    value = om.group(2)
    cm = INLINE_COMMENT.search(value)
    body, comment = (value[:cm.start()], value[cm.start():]) if cm else (value, "")
    return head + ",".join(rewrite_value(p, m) if p.strip() else p for p in body.split(",")) + comment


def apply(config, m, out):
    """Copy the config and its includes under out (same layout below their common folder), pins rewritten.
    Returns the copy of config."""
    files = load(config).files
    root = os.path.commonpath([os.path.dirname(f) for f in files])
    for path in files:
        dst = os.path.join(out, os.path.relpath(path, root))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(path) as f:
            text = f.read()
        lines = [_rewrite_line(l, m) for l in text.split("\n")]
        with open(dst, "w") as f:
            f.write("\n".join(lines))
    return os.path.join(out, os.path.relpath(os.path.abspath(config), root)), len(files)


def _write_map(path, m):
    with open(path, "w") as f:
        json.dump(m, f, indent=2)
        f.write("\n")


def main(argv):
    ap = argparse.ArgumentParser(prog="pinmap", description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("action", choices=["generate", "check", "apply"])
    ap.add_argument("--config", required=True, help="the printer's top config file")
    ap.add_argument("--map", required=True, help="the pin map (JSON), written by generate")
    ap.add_argument("--target", default=DEFAULT_TARGET, choices=sorted(TARGETS), help="generate: the simulated board")
    ap.add_argument("--out", help="apply: folder for the rewritten config tree")
    a = ap.parse_args(argv)
    uses = pin_uses(load(a.config))
    if a.action == "generate":
        previous = None
        if os.path.exists(a.map):
            with open(a.map) as f:
                previous = json.load(f)
        m = generate(uses, previous, a.target)
        _write_map(a.map, m)
        n = sum(len(p) for p in m["mcus"].values())
        return [f"pinmap: wrote {a.map}: {n} pins on {len(m['mcus'])} simulated {a.target} boards"]
    with open(a.map) as f:
        m = json.load(f)
    problems = check(uses, m)
    if a.action == "check":
        if not problems:
            return ["pinmap: OK"]
        return [f"pinmap: {p}" for p in problems] + [
            f"pinmap: regenerate with: python3 {os.path.relpath(__file__)} generate --config {a.config} "
            f"--map {a.map}", "pinmap: FAILED"]
    if problems:
        raise ValueError("the map doesn't match the config; run check: " + "; ".join(problems))
    if not a.out:
        ap.error("apply needs --out")
    top, n = apply(a.config, m, a.out)
    return [f"pinmap: wrote {n} files under {a.out}", f"pinmap: config {top}"]


def cli(argv):
    try:
        out = main(argv)
    except ValueError as e:
        print(f"pinmap: {e}\npinmap: FAILED")
        return 1
    print("\n".join(out))
    return 1 if out[-1] == "pinmap: FAILED" else 0


if __name__ == "__main__":
    sys.exit(cli(sys.argv[1:]))
