#!/usr/bin/env python3
"""Check parts/printed/ against its manifest and the printed-parts list (#63 AC6).

Fails (exit 1) when:
  - a manifest row's file is missing, or its sha256 doesn't match;
  - a printable file (.stl, .3mf) under parts/printed/ isn't in the manifest;
  - a "print" row in bom/printed-parts.md has no manifest row (no part and no link);
  - a manifest row names a bom row that isn't in bom/printed-parts.md;
  - a row has no stage, or a stage outside the stage issues #7-#15 (#40);
  - a row's qty isn't a whole number or "as-needed";
  - a row has neither a path nor a link, or a path appears twice;
  - a committed part has no LICENSE (unless it's the user's own design, under the root LICENSE) or no README.md
    in its folder or a parent folder under parts/printed/;
  - a copy of an in-repo part (repo = this repo, upstream_path set) differs from its source;
  - the generated table in parts/printed/README.md is out of date (rewrite it with --write-index).

--upstream also downloads each upstream file at its pinned commit and compares sha256
(needs the network, so CI doesn't run it).

Stdlib only. Usage:
  python3 platform/parts/check-printed.py [--root DIR] [--write-index] [--upstream]
"""
import argparse
import csv
import hashlib
import os
import re
import sys
import urllib.parse
import urllib.request

THIS_REPO = "dvystrcil/vt350"
REPO_LICENSE = "GPL-3.0-or-later"   # the root LICENSE: the user's own work (vt350#122)
PRINTED = "parts/printed"
MANIFEST = f"{PRINTED}/manifest.csv"
README = f"{PRINTED}/README.md"
BOM = "bom/printed-parts.md"
COLUMNS = ["path", "part", "qty", "stage", "bom", "source", "repo", "commit", "upstream_path",
           "sha256", "license", "variant", "link", "material", "notes"]
PRINTABLE = (".stl", ".3mf")
STAGES = range(7, 16)
BEGIN = "<!-- BEGIN GENERATED by platform/parts/check-printed.py --write-index: do not edit by hand -->"
END = "<!-- END GENERATED -->"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_manifest(root):
    with open(os.path.join(root, MANIFEST), newline="") as f:
        r = csv.DictReader(f)
        if r.fieldnames != COLUMNS:
            raise SystemExit(f"{MANIFEST}: columns are {r.fieldnames}, expected {COLUMNS}")
        return list(r)


def bom_key(cell):
    """A bom row's key: its first cell, with markdown links reduced to their text and backticks removed."""
    cell = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", cell)
    return re.sub(r"\s+", " ", cell.replace("`", "")).strip()


def split_row(line):
    # split on | that isn't inside backticks
    cells, cur, tick = [], "", False
    for ch in line.strip().strip("|"):
        if ch == "`":
            tick = not tick
        if ch == "|" and not tick:
            cells.append(cur.strip())
            cur = ""
        else:
            cur += ch
    cells.append(cur.strip())
    return cells


def load_bom(root):
    """{key: status} for every row of every table in bom/printed-parts.md that has a Status column."""
    rows, status_col = {}, None
    lines = read(os.path.join(root, BOM)).splitlines()
    for i, line in enumerate(lines):
        if not line.lstrip().startswith("|"):
            status_col = None
            continue
        cells = split_row(line)
        if status_col is None:
            low = [c.lower() for c in cells]
            nxt = lines[i + 1] if i + 1 < len(lines) else ""
            if "status" in low and re.match(r"^\s*\|[\s:|-]+\|\s*$", nxt):
                status_col = low.index("status")
            continue
        if re.match(r"^[\s:-]*$", "".join(cells)):
            continue  # the |---| separator
        if len(cells) > status_col:
            rows[bom_key(cells[0])] = cells[status_col].strip().lower()
    return rows


def read(path):
    with open(path) as f:
        return f.read()


def find_up(root, rel_dir, name):
    """Is `name` in rel_dir or a parent of it, below parts/printed/ (its own README is the index, not a source's)?"""
    parts = rel_dir.split("/") if rel_dir else []
    while parts:
        if os.path.exists(os.path.join(root, PRINTED, *parts, name)):
            return True
        parts.pop()
    return False


def full_set(rows):
    """Totals for one full set. Rows sharing a variant are alternatives: count one of them."""
    pieces, files, as_needed, seen = 0, 0, 0, set()
    for r in rows:
        if not r["path"]:
            continue
        if r["variant"]:
            if r["variant"] in seen:
                continue
            seen.add(r["variant"])
        files += 1
        if r["qty"] == "as-needed":
            as_needed += 1
        elif r["qty"].isdigit():
            pieces += int(r["qty"])
    return {"pieces": pieces, "files": files, "as_needed": as_needed}


def md_link_path(rel):
    return urllib.parse.quote(rel)


def render_index(rows):
    out = [BEGIN, "", "| Part | Qty | Stage | Source | Licence | Material / print notes | File |",
           "|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (int(r["stage"]) if r["stage"].isdigit() else 99, r["source"], r["part"])):
        notes = "; ".join(x for x in (r["material"], r["notes"], f"alternative: {r['variant']}" if r["variant"] else "") if x)
        if r["path"]:
            f = f"[`{r['path']}`]({md_link_path(r['path'])})"
        else:
            f = f"link only: [upstream]({r['link']})"
        out.append(f"| {r['part']} | {r['qty']} | #{r['stage']} | {r['source']} | {r['license']} | {notes} | {f} |")
    t = full_set(rows)
    links = sum(1 for r in rows if not r["path"])
    out += ["", f"**Full set:** {t['pieces']} printed pieces from {t['files']} files"
            + (f", plus {t['as_needed']} file(s) printed as needed" if t["as_needed"] else "")
            + (f". {links} part(s) are links only, not counted" if links else "")
            + ". Rows marked *alternative* are pick-one: one of each group is counted.", "", END]
    return "\n".join(out)


def write_index(root):
    p = os.path.join(root, README)
    text = read(p) if os.path.exists(p) else f"# Printed parts\n\n{BEGIN}\n{END}\n"
    if BEGIN not in text or END not in text:
        text += f"\n{BEGIN}\n{END}\n"
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    with open(p, "w") as f:
        f.write(head + render_index(load_manifest(root)) + tail)


def check(root):
    errs = []
    rows = load_manifest(root)
    bom = load_bom(root)
    paths = set()
    for n, r in enumerate(rows, start=2):
        where = f"{MANIFEST}:{n} ({r['path'] or r['part']})"
        if not r["path"] and not r["link"]:
            errs.append(f"{where}: neither a path nor a link")
        if not r["stage"].isdigit() or int(r["stage"]) not in STAGES:
            errs.append(f"{where}: stage {r['stage']!r} is not a stage issue #7-#15")
        if not (r["qty"].isdigit() or r["qty"] == "as-needed"):
            errs.append(f"{where}: qty {r['qty']!r} is not a whole number or 'as-needed'")
        if r["bom"] not in bom:
            errs.append(f"{where}: bom {r['bom']!r} is not a row in {BOM}")
        if not r["path"]:
            continue
        if r["path"] in paths:
            errs.append(f"{where}: duplicate path")
        paths.add(r["path"])
        full = os.path.join(root, PRINTED, r["path"])
        if not os.path.isfile(full):
            errs.append(f"{where}: manifest row has no file")
            continue
        got = sha256(full)
        if got != r["sha256"]:
            errs.append(f"{where}: sha256 mismatch (manifest {r['sha256'][:12]}, file {got[:12]})")
        folder = os.path.dirname(r["path"])
        own = r["repo"] == THIS_REPO and not r["upstream_path"]   # the user's own design, not a copy or remix
        if own and r["license"] != REPO_LICENSE:
            errs.append(f"{where}: own design must carry the repo licence {REPO_LICENSE}, not {r['license']!r}")
        if not own and not find_up(root, folder, "LICENSE"):
            errs.append(f"{where}: no LICENSE in its folder or a parent under {PRINTED}/")
        if not find_up(root, folder, "README.md"):
            errs.append(f"{where}: no README.md in its folder or a parent under {PRINTED}/")
        if r["repo"] == THIS_REPO and r["upstream_path"]:
            src = os.path.join(root, r["upstream_path"])
            if not os.path.isfile(src) or sha256(src) != got:
                errs.append(f"{where}: differs from its source {r['upstream_path']} (re-copy it and update sha256)")
    for dirpath, _, files in os.walk(os.path.join(root, PRINTED)):
        for fn in files:
            if fn.lower().endswith(PRINTABLE):
                rel = os.path.relpath(os.path.join(dirpath, fn), os.path.join(root, PRINTED))
                if rel not in paths:
                    errs.append(f"{PRINTED}/{rel}: printable file not in manifest")
    covered = {r["bom"] for r in rows}
    for key, status in bom.items():
        if status.startswith("print") and key not in covered:
            errs.append(f"{BOM}: print row {key!r} has no part or link in the manifest")
    readme = os.path.join(root, README)
    text = read(readme) if os.path.exists(readme) else ""
    if render_index(rows) not in text:
        errs.append(f"{README}: generated index is out of date (run platform/parts/check-printed.py --write-index)")
    return errs


def check_upstream(root):
    errs = []
    for r in load_manifest(root):
        if not r["path"] or r["repo"] == THIS_REPO:
            continue
        url = (f"https://raw.githubusercontent.com/{r['repo']}/{r['commit']}/"
               + urllib.parse.quote(r["upstream_path"]))
        try:
            with urllib.request.urlopen(url, timeout=60) as resp:
                got = hashlib.sha256(resp.read()).hexdigest()
        except Exception as e:  # report, don't hide: a failed fetch is a failed check
            errs.append(f"{r['path']}: could not fetch {url}: {e}")
            continue
        status = "ok" if got == r["sha256"] else "MISMATCH"
        print(f"upstream {status:8s} {r['repo']}@{r['commit'][:7]} {r['upstream_path']}")
        if got != r["sha256"]:
            errs.append(f"{r['path']}: upstream file at {r['commit'][:7]} has sha256 {got[:12]}, manifest {r['sha256'][:12]}")
    return errs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    ap.add_argument("--write-index", action="store_true", help=f"rewrite the generated table in {README}")
    ap.add_argument("--upstream", action="store_true", help="also compare each file with its upstream (network)")
    a = ap.parse_args()
    if a.write_index:
        write_index(a.root)
    errs = check(a.root) + (check_upstream(a.root) if a.upstream else [])
    rows = load_manifest(a.root)
    for e in errs:
        print(f"FAIL {e}")
    t = full_set(rows)
    print(f"{len(rows)} manifest rows, {t['files']} files in a full set, {len(errs)} problem(s)")
    print("check-printed: " + ("FAILED" if errs else "OK"))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
