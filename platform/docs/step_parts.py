#!/usr/bin/env python3
"""Per-step Print and Buy tables for the assembly pages (vt350#40 AC3).

Each assembly page `<pages>/stage-N-<name>.md` gets the parts for stage N only, written between two marker lines:

    <!-- step-parts:begin -->
    ...generated: do not edit by hand...
    <!-- step-parts:end -->

  - **Print**: the printed-parts manifest's rows for stage N: part, qty, file, licence. The file links into the
    printed-parts folder (relative to the page) when the file is committed there; otherwise to the row's `link`, or
    to the upstream file at its pinned commit (`repo` + `commit` + `upstream_path`, on GitHub). Rows that share a
    `variant` are alternatives: the part cell says so. Rows with qty 0 are kept in the manifest for reference
    (replaced parts) and left out of the table.
  - **Buy**: the BOM's rows for stage N: item, qty (`qty_needed`), status, vendor (linked to `link` when it has one).
    A row in category `per head` lists the parts for ONE toolhead: its qty reads "3 per head".

The two sources spell the stage differently, and both are accepted as they are (#40 AC2):
  - the manifest's `stage` column is a bare number: `12`;
  - the BOM's `stage` column is an issue reference: `#12`.

--check (what CI runs) writes nothing and fails (exit 1) when:
  - a page's generated block is stale (rewrite it: run without --check);
  - a page for a stage with parts has no markers, or its markers are broken (missing, repeated or out of order);
  - two pages claim the same stage, or a row's stage isn't a number (with or without "#").
Stages that have parts but no page yet are listed as a warning, not a failure: pages are written one stage at a time.

Stdlib only; reads the printer's data, imports none of its code. Usage (from the repo root):
  python3 platform/docs/step_parts.py [--root DIR] [--manifest CSV] [--printed DIR] [--bom CSV] [--pages DIR]
  python3 platform/docs/step_parts.py --check      # last line "step-parts: OK"
Paths are relative to --root (default: this checkout). Defaults: parts/printed/manifest.csv, parts/printed,
bom/bom.csv, docs/assembly.
"""
import argparse
import csv
import os
import re
import sys
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BEGIN = "<!-- step-parts:begin -->"
END = "<!-- step-parts:end -->"
NOTE = ("<!-- Generated by platform/docs/step_parts.py from {manifest} and {bom}: "
        "edit those, then re-run it. -->")
PER_HEAD = "per head"  # BOM category whose qty_needed is for one toolhead
PAGE_RE = re.compile(r"stage-(\d+)-.+\.md\Z")


class StepPartsError(Exception):
    pass


def stage_of(text, where):
    """The stage number from "12" or "#12"; None when empty."""
    t = text.strip()
    if not t:
        return None
    m = re.fullmatch(r"#?(\d+)", t)
    if not m:
        raise StepPartsError(f"{where}: stage {text!r} isn't a number like 12 or #12")
    return int(m.group(1))


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def by_stage(rows, name):
    out = {}
    for i, r in enumerate(rows, start=2):  # line 1 is the header
        s = stage_of(r.get("stage") or "", f"{name} line {i}")
        if s is not None:
            out.setdefault(s, []).append(r)
    return out


def cell(text):
    """Text safe inside a markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def link(text, url):
    text = cell(text).replace("[", "\\[").replace("]", "\\]")
    return f"[{text}]({url})"


def print_file(r, printed_dir, page_dir):
    """A markdown link to the part's file, or "" when there's nothing to link."""
    path = (r.get("path") or "").strip()
    if path and os.path.isfile(os.path.join(printed_dir, path)):
        rel = os.path.relpath(os.path.join(printed_dir, path), page_dir).replace(os.sep, "/")
        return link(os.path.basename(path), urllib.parse.quote(rel))
    if (r.get("link") or "").strip():
        return link("upstream", r["link"].strip())
    repo, commit, up = (r.get(k, "").strip() for k in ("repo", "commit", "upstream_path"))
    if repo and commit and up:
        url = f"https://github.com/{repo}/blob/{commit}/{urllib.parse.quote(up)}"
        return link(os.path.basename(up) + " (upstream)", url)
    return ""


def print_table(rows, printed_dir, page_dir):
    rows = [r for r in rows if (r.get("qty") or "").strip() != "0"]
    if not rows:
        return ["Nothing to print for this step."]
    out = ["| Print | Qty | File | Licence |", "|---|---|---|---|"]
    for r in rows:
        part = cell(r.get("part", ""))
        if (r.get("variant") or "").strip():
            part += f" (alternatives `{cell(r['variant'])}`: print one)"
        out.append(f"| {part} | {cell(r.get('qty', ''))} | {print_file(r, printed_dir, page_dir)} | "
                   f"{cell(r.get('license', ''))} |")
    return out


def buy_table(rows):
    if not rows:
        return ["Nothing to buy for this step."]
    out = ["| Buy | Qty | Status | Vendor |", "|---|---|---|---|"]
    for r in rows:
        qty = cell(r.get("qty_needed", ""))
        if (r.get("category") or "").strip() == PER_HEAD:
            qty += " per head"
        vendor, url = (r.get("vendor") or "").strip(), (r.get("link") or "").strip()
        vend = link(vendor or "link", url) if url else cell(vendor)
        out.append(f"| {cell(r.get('item', ''))} | {qty} | {cell(r.get('status', ''))} | {vend} |")
    return out


def block(stage_prints, stage_buys, printed_dir, page_dir, note):
    lines = [BEGIN, note, ""]
    lines += print_table(stage_prints, printed_dir, page_dir)
    lines += [""]
    lines += buy_table(stage_buys)
    lines += [END]
    return "\n".join(lines)


def find_pages(pages_dir):
    """{stage: page path}; two pages for one stage is an error."""
    pages = {}
    if not os.path.isdir(pages_dir):
        return pages
    for name in sorted(os.listdir(pages_dir)):
        m = PAGE_RE.match(name)
        if not m:
            continue
        s = int(m.group(1))
        if s in pages:
            raise StepPartsError(f"stage {s} has two pages: {os.path.basename(pages[s])} and {name}")
        pages[s] = os.path.join(pages_dir, name)
    return pages


def replace_block(text, new_block, page):
    """The page's text with its block replaced; None when it has no markers at all."""
    nb, ne = text.count(BEGIN), text.count(END)
    if nb == 0 and ne == 0:
        return None
    if nb != 1 or ne != 1 or text.index(BEGIN) > text.index(END):
        raise StepPartsError(f"{page}: needs exactly one {BEGIN} followed by one {END}")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + new_block + tail


def run(root, manifest, printed, bom, pages_dir, check):
    """(errors, warnings, written pages)."""
    p = lambda x: x if os.path.isabs(x) else os.path.join(root, x)
    prints = by_stage(read_csv(p(manifest)), manifest)
    buys = by_stage(read_csv(p(bom)), bom)
    pages = find_pages(p(pages_dir))
    note = NOTE.format(manifest=manifest, bom=bom)
    errors, warnings, written = [], [], []
    for s in sorted(set(prints) | set(buys)):
        if s not in pages:
            warnings.append(f"stage {s} has parts but no page ({pages_dir}/stage-{s}-*.md)")
    for s, page in sorted(pages.items()):
        rel = os.path.relpath(page, root)
        with open(page, encoding="utf-8") as f:
            text = f.read()
        new_block = block(prints.get(s, []), buys.get(s, []), p(printed), os.path.dirname(page), note)
        try:
            new = replace_block(text, new_block, rel)
        except StepPartsError as e:
            errors.append(str(e))
            continue
        if new is None:
            if s in prints or s in buys:
                errors.append(f"{rel}: stage {s} has parts but the page has no {BEGIN} / {END} markers")
            continue
        if new != text:
            if check:
                errors.append(f"{rel}: the parts block is stale; run python3 platform/docs/step_parts.py")
            else:
                with open(page, "w", encoding="utf-8") as f:
                    f.write(new)
                written.append(rel)
    return errors, warnings, written


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--manifest", default="parts/printed/manifest.csv")
    ap.add_argument("--printed", default="parts/printed")
    ap.add_argument("--bom", default="bom/bom.csv")
    ap.add_argument("--pages", default="docs/assembly")
    ap.add_argument("--check", action="store_true", help="write nothing; fail if a page is stale")
    a = ap.parse_args(argv)
    try:
        errors, warnings, written = run(a.root, a.manifest, a.printed, a.bom, a.pages, a.check)
    except (StepPartsError, OSError) as e:
        errors, warnings, written = [str(e)], [], []
    for w in warnings:
        print(f"warning: {w}")
    for w in written:
        print(f"wrote {w}")
    for e in errors:
        print(f"FAIL: {e}")
    if errors:
        print("step-parts: FAILED")
        return 1
    print("step-parts: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
